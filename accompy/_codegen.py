"""Write the tables the TypeScript twin shares with Python as ``ts/src/data.generated.ts``.

Every table the engine reads lives once, in Python: the builtin style patterns, the
rhythmic skeletons, the chord-symbol rewrites, the transposition spellings, the defaults
of :class:`~accompy.base.AccompanimentConfig`, and the root and quality tables of the
``tonal`` package that the default chord resolver reads. This module renders them as
JSON literals (``as const``) for the TypeScript twin in ``ts/``.

A mapping whose keys could look like integers (``tonal``'s quality table has ``"7"``,
``"9"``, ...) is emitted as a list of ``[key, value]`` pairs, since a JavaScript object
would move such keys first and its order is part of the lookup.

Run ``python -m accompy._codegen`` after editing a table; ``tests/test_twin.py`` fails
while the committed TypeScript file differs from what this module renders (including
when a new ``tonal`` release changes its tables).

>>> 'export const DRUM_PATTERNS' in render_ts()
True
"""

from __future__ import annotations

import json
from pathlib import Path

#: The repository root (where ``ts/`` lives, next to the package).
REPO_ROOT = Path(__file__).resolve().parent.parent

#: Where the TypeScript twin keeps the generated tables, relative to the repository root.
TS_DATA_PATH = Path("ts") / "src" / "data.generated.ts"

_HEADER = """\
// GENERATED by `python -m accompy._codegen` from the Python package's tables. Do not
// edit: edit the Python source and regenerate (tests/test_twin.py checks it is current).
"""


def _drum(p):
    return {
        "name": p.name,
        "beats_per_bar": p.beats_per_bar,
        "hits": [[h.beat, h.drum, h.velocity] for h in p.hits],
    }


def _bass(p):
    return {
        "name": p.name,
        "notes": [[n.beat, n.pitch_offset, n.duration, n.velocity] for n in p.notes],
    }


def _comp(p):
    return {"name": p.name, "hits": [list(h) for h in p.hits]}


def shared_tables() -> dict:
    """The tables the twin shares, by their TypeScript name, in JSON form."""
    from tonal.notes import chord_quality, root_notes

    from accompy import util
    from accompy.base import AccompanimentConfig
    from accompy.chord_resolution import DFLT_CHORD_TRANSPOSE_SEMITONES
    from accompy.patterns import builtin, dataclasses as pattern_dataclasses
    from accompy.renderers import midi
    from accompy.rhythmic_skeletons import RHYTHMIC_SKELETONS

    defaults = AccompanimentConfig()
    return {
        "DRUM_PATTERNS": {
            s: [_drum(p) for p in ps] for s, ps in builtin.DRUM_PATTERNS.items()
        },
        "BASS_PATTERNS": {
            s: [_bass(p) for p in ps] for s, ps in builtin.BASS_PATTERNS.items()
        },
        "COMP_PATTERNS": {
            s: [_comp(p) for p in ps] for s, ps in builtin.COMP_PATTERNS.items()
        },
        "DRUMS": {
            n: getattr(pattern_dataclasses, n)
            for n in vars(pattern_dataclasses)
            if n.isupper() and isinstance(getattr(pattern_dataclasses, n), int)
        },
        "RHYTHMIC_SKELETONS": {
            k: {**v, "pattern": list(v["pattern"])}
            for k, v in RHYTHMIC_SKELETONS.items()
        },
        "CHORD_SYMBOL_REPLACEMENTS": util.CHORD_SYMBOL_REPLACEMENTS,
        "UNNORMALIZED_SYMBOLS": util.UNNORMALIZED_SYMBOLS,
        "SHARP_NOTES": util._SHARP_NOTES,
        "FLAT_NOTES": util._FLAT_NOTES,
        "NOTE_TO_SEMITONE": list(util._NOTE_TO_SEMITONE.items()),
        "FLAT_KEYS": sorted(util._FLAT_KEYS),
        "NO_CHORD_SYMBOLS": midi.NO_CHORD_SYMBOLS,
        "FALLBACK_CHORD_NOTES": midi.FALLBACK_CHORD_NOTES,
        "DEFAULT_INSTRUMENTS": defaults.instruments,
        "DEFAULT_VOLUMES": defaults.volumes,
        "DEFAULT_TRANSPOSE": DFLT_CHORD_TRANSPOSE_SEMITONES,
        "TONAL_ROOT_NOTES": list(root_notes.items()),
        "TONAL_CHORD_QUALITY": [[k, list(v)] for k, v in chord_quality.items()],
        "PY_WHITESPACE": whitespace_code_points(),
    }


def whitespace_code_points() -> list[int]:
    """Every code point ``str.isspace`` accepts (what ``str.strip`` and ``str.split`` cut)."""
    import sys

    return [c for c in range(sys.maxunicode + 1) if chr(c).isspace()]


def _jsonable(value):
    if isinstance(value, (tuple, list)):
        return [_jsonable(v) for v in value]
    if isinstance(value, dict):
        return {str(k): _jsonable(v) for k, v in value.items()}
    return value


def render_ts() -> str:
    """The TypeScript source of the shared tables, exactly as it should be committed."""
    lines = [_HEADER]
    for name, value in shared_tables().items():
        literal = json.dumps(_jsonable(value), ensure_ascii=False)
        lines.append(f"export const {name} = {literal} as const;")
    return "\n".join(lines) + "\n"


def write_ts(root: Path | str = REPO_ROOT) -> Path:
    """Write :func:`render_ts` to ``<root>/ts/src/data.generated.ts``; return the path."""
    path = Path(root) / TS_DATA_PATH
    path.write_text(render_ts(), encoding="utf-8")
    return path


if __name__ == "__main__":
    print(write_ts())
